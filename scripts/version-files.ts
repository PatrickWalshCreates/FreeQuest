// Every place FreeQuest's version is written. The root package.json is the
// source; `pnpm version:set <version>` writes it everywhere else, and a test
// (packages/schema/test/version.test.ts) fails if any copy drifts.
import { readFileSync, readdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';

/** Plain semver: 1.2.3, optionally with a pre-release like 0.1.0-beta.1. */
export const VERSION_PATTERN = /^\d+\.\d+\.\d+(-[0-9A-Za-z.-]+)?$/;

export interface VersionedFile {
  /** Repo-relative path. */
  readonly path: string;
  /** The version written in it (null if it can't be found). */
  read(text: string): string | null;
  /** The text with the version replaced. */
  write(text: string, version: string): string;
}

const jsonVersion: Omit<VersionedFile, 'path'> = {
  read: (text) => {
    const v = (JSON.parse(text) as { version?: unknown }).version;
    return typeof v === 'string' ? v : null;
  },
  // Only the first "version" key: the package's own (dependencies come later).
  write: (text, version) => text.replace(/"version": "[^"]*"/, `"version": "${version}"`),
};

const cargoToml: Omit<VersionedFile, 'path'> = {
  read: (text) => /^\[package\][^[]*?^version = "([^"]*)"/ms.exec(text)?.[1] ?? null,
  write: (text, version) =>
    text.replace(/^(\[package\][^[]*?^version = ")[^"]*(")/ms, `$1${version}$2`),
};

/** A crate's own entry in a Cargo.lock. */
function cargoLock(crate: string): Omit<VersionedFile, 'path'> {
  const entry = new RegExp(`(name = "${crate}"\\nversion = ")([^"]*)(")`);
  return {
    read: (text) => entry.exec(text)?.[2] ?? null,
    write: (text, version) => text.replace(entry, `$1${version}$3`),
  };
}

const generated: Omit<VersionedFile, 'path'> = {
  read: (text) => /FREEQUEST_VERSION = '([^']*)'/.exec(text)?.[1] ?? null,
  write: (_text, version) =>
    `// Generated by \`pnpm version:set\` from the root package.json: don't edit by hand.\n` +
    `/** The version of FreeQuest (the engine, editor, player and CLI share one). */\n` +
    `export const FREEQUEST_VERSION = '${version}';\n`,
};

export const VERSION_SOURCE = 'package.json';
export const GENERATED_VERSION_FILE = 'packages/schema/src/version.ts';

/** Every versioned file except the source, in a stable order. */
export function versionedFiles(root: string): VersionedFile[] {
  const packages = ['packages', 'apps'].flatMap((dir) =>
    readdirSync(join(root, dir), { withFileTypes: true })
      .filter((e) => e.isDirectory() && existsSync(join(root, dir, e.name, 'package.json')))
      .map((e) => `${dir}/${e.name}/package.json`)
      .sort(),
  );
  return [
    ...packages.map((path) => ({ path, ...jsonVersion })),
    { path: 'apps/editor/src-tauri/tauri.conf.json', ...jsonVersion },
    { path: 'apps/player-desktop/src-tauri/tauri.conf.json', ...jsonVersion },
    { path: 'apps/editor/src-tauri/Cargo.toml', ...cargoToml },
    { path: 'apps/player-desktop/src-tauri/Cargo.toml', ...cargoToml },
    { path: 'apps/editor/src-tauri/Cargo.lock', ...cargoLock('freequest-editor') },
    { path: 'apps/player-desktop/src-tauri/Cargo.lock', ...cargoLock('freequest-player') },
    { path: GENERATED_VERSION_FILE, ...generated },
  ];
}

/** The version in the root package.json. */
export function sourceVersion(root: string): string {
  const version = jsonVersion.read(readFileSync(join(root, VERSION_SOURCE), 'utf8'));
  if (!version) throw new Error(`no "version" in ${VERSION_SOURCE}`);
  return version;
}
